"""
Interactive shell mode for IntelliTerm.

Provides a REPL (Read-Eval-Print Loop) where users can type natural
language queries or standard shell commands. This mode is launched
via 'turn shell' and runs until the user types 'exit' or 'quit'.

The shell handles two types of input:
- Direct commands (git, pip, ls, etc.) are executed immediately.
- Natural language queries are sent to the AI for translation.
"""

import os
from . import core
from . import executor
from . import history
from . import config
from . import safety
from . import ui


def _handle_ai_query(prompt):
    """
    Process a natural language query through the full AI pipeline.

    Flow: AI call -> clarification (if needed) -> safety check ->
    confirmation (Y/N/E) -> execution -> save to history.

    Args:
        prompt: The natural language query string.
    """
    # Call the AI with a loading spinner
    with ui.get_spinner():
        response = core.get_ai_response(prompt)

    # Handle API or parsing errors
    if response.get("status") == "error":
        ui.print_error(response.get("message", "Unknown error"))
        return

    # Handle clarification requests
    if response.get("status") == "incomplete":
        question = response.get("question", "Please provide more details.")
        ui.print_clarification_box(question)
        clarification = ui.prompt_input(">>>")

        if not clarification.strip():
            ui.print_info("Action cancelled.")
            return

        # Re-query with the additional information
        combined_prompt = (
            f"Original request was '{prompt}'. "
            f"The user provided this missing info: '{clarification}'"
        )
        with ui.get_spinner():
            response = core.get_ai_response(combined_prompt)

        if response.get("status") != "success":
            msg = response.get(
                "message",
                response.get("question", "Could not process request."),
            )
            ui.print_error(msg)
            return

    # Handle successful command generation
    if response.get("status") == "success":
        command = response.get("command", "")
        explanation = response.get("explanation", "")
        _confirm_and_execute(prompt, command, explanation)


def _confirm_and_execute(original_prompt, command, explanation):
    """
    Display a command suggestion, handle the Y/N/E confirmation
    loop, and execute the final command.

    In Power User Mode, confirmation is skipped unless the command
    is flagged as dangerous by the safety checker.

    Args:
        original_prompt: The user's original query (for edit context).
        command: The shell command generated by the AI.
        explanation: The AI's explanation of the command.
    """
    current_command = command
    current_explanation = explanation
    power_mode = config.get_power_mode()

    while True:
        # Display the suggestion
        ui.print_command_box(current_command, current_explanation)

        # Safety check runs regardless of power mode
        is_dangerous, danger_reason = safety.check_safety(current_command)
        if is_dangerous:
            ui.print_danger_warning(current_command, danger_reason)
            confirm = ui.prompt_input(
                "Type 'confirm' to proceed, or anything else to cancel:"
            )
            if confirm.strip().lower() != "confirm":
                ui.print_info("Action cancelled.")
                return
            break

        # Power User Mode skips the Y/N/E prompt
        if power_mode:
            break

        # Normal mode: ask for confirmation
        choice = ui.prompt_confirm()

        if choice in ("y", "yes", ""):
            break
        elif choice in ("n", "no"):
            ui.print_info("Action cancelled.")
            return
        elif choice in ("e", "edit"):
            edit_request = ui.prompt_input("Describe your change:")
            if not edit_request.strip():
                ui.print_info("Edit cancelled, no change described.")
                continue

            # Ask AI to revise the command
            with ui.get_spinner():
                response = core.get_edit_response(
                    original_prompt, current_command, edit_request
                )

            if response.get("status") == "success":
                current_command = response.get("command", current_command)
                current_explanation = response.get(
                    "explanation", current_explanation
                )
            else:
                ui.print_error(
                    "Could not process edit: "
                    + response.get("message", "Unknown error")
                )
            continue
        else:
            ui.print_info("Invalid choice. Please enter Y, N, or E.")

    # Execute the confirmed command
    ui.print_executing(current_command)
    stdout, stderr = executor.handle_execution(current_command)
    ui.print_output(stdout, stderr)

    # Save to history
    history.save_entry(original_prompt, current_command)


def run():
    """
    Start the interactive shell loop.

    This is the main REPL that displays the banner, handles user input,
    routes direct commands to the shell, and sends natural language
    queries through the AI pipeline.

    The loop runs until the user types 'exit', 'quit', or presses
    Ctrl+C.
    """
    # Verify API key is configured before starting
    api_key = config.get_api_key()
    if not api_key:
        ui.print_error("API key not configured.")
        ui.print_info("Run: turn config set-key <your-groq-api-key>")
        return

    ui.print_banner()

    while True:
        try:
            prompt = ui.prompt_input(f"\n{os.getcwd()}>")

            if not prompt.strip():
                continue

            if prompt.strip().lower() in ("exit", "quit"):
                ui.print_info("Goodbye.")
                break

            # Direct commands bypass the AI entirely
            if executor.is_direct_command(prompt):
                stripped = prompt.strip()
                if stripped.lower().startswith("cd "):
                    parts = stripped.split(" ", 1)
                    if len(parts) > 1:
                        success, message = executor.handle_cd(parts[1])
                        if success:
                            ui.print_success(message)
                        else:
                            ui.print_error(message)
                else:
                    stdout, stderr = executor.execute_command(prompt)
                    ui.print_output(stdout, stderr)
                continue

            # Everything else is a natural language query
            _handle_ai_query(prompt)

        except KeyboardInterrupt:
            ui.console.print()
            ui.print_info("Goodbye.")
            break
        except EOFError:
            ui.print_info("Goodbye.")
            break
